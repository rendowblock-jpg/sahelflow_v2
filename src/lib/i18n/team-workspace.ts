export type TeamAreaAccess = "edit" | "view" | "use";

/** How a permission set reads area by area; areas without access are omitted. */
export function summarizeTeamAccess(
  permissions: readonly Phase2Action[],
): Array<{ area: TeamArea; access: TeamAreaAccess }> {
  const has = (actions: readonly Phase2Action[] | undefined) =>
    Boolean(actions?.some((action) => permissions.includes(action)));
  return TEAM_AREAS.flatMap((area) => {
    if (!has(area.view) && !has(area.edit)) return [];
    const access: TeamAreaAccess = area.use
      ? "use"
      : has(area.edit)
        ? "edit"
        : "view";
    return [{ area, access }];
  });
}
