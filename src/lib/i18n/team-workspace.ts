export type TeamCopyKey = keyof typeof copy.en;

/** The full catalog, exposed for the locale-parity contract. */
export const TEAM_COPY_CATALOG: Readonly<Record<Locale, Readonly<Record<string, string>>>> = copy;

export function getTeamCopy(
  locale: Locale,
  key: TeamCopyKey,
  params?: Record<string, string | number>,
): string {
  const template: string = (copy[locale] as Record<string, string>)[key] ?? copy.en[key];
  return params
    ? template.replace(/\{\{(\w+)\}\}/g, (_, name: string) =>
        String(params[name] ?? `{{${name}}}`),
      )
    : template;
}

